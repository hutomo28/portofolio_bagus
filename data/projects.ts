function getYouTubeId(url: string): string {
  const match = url.match(/(?:youtu\.be\/|v=)([^&?/]+)/);
  return match ? match[1] : '';
}

function getInstagramId(url: string): string {
  const match = url.match(/reel\/([^/?]+)/);
  return match ? match[1] : url;
}

